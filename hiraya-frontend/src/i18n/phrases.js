/** Build per-language lookup maps once. */
const build = (column) => {
  const map = new Map();
  PHRASE_ROWS.forEach((row) => {
    const key = row[0].replace(/\s+/g, ' ').trim();
    if (row[column] && !map.has(key)) map.set(key, row[column]);
  });
  return map;
};

